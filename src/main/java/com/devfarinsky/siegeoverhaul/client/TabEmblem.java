    private final int color;
    private final char[][] cells = new char[32][32];

    TabEmblem(int color, String... rows) {
        this.color = color;
        for (int y = 0; y < 32; y++) {
            String row = y < rows.length ? rows[y] : "";
            for (int x = 0; x < 32; x++) {
                cells[y][x] = x < row.length() ? row.charAt(x) : ' ';
            }
        }
    }

    public int color() { return color; }

    public void draw(GuiGraphics g, int x, int y, int size) {
        int cell = Math.max(1, size / 32);
        int inset = (size - cell * 32) / 2;

        int highlight = brighten(color, 0x28);
        int outline = 0xff17110c;
        int shadow = 0xff0a0d18;

        for (int row = 0; row < 32; row++) {
            for (int col = 0; col < 32; col++) {
                char c = cells[row][col];
                if (c == ' ') continue;
                int px = x + inset + col * cell;
                int py = y + inset + row * cell;
                // Drop shadow (offset by 1 pixel).
                g.fill(px + 1, py + 1, px + cell + 1, py + cell + 1, shadow);
                int fill = switch (c) {
                    case '.' -> outline;
                    case '=' -> highlight;
                    default -> color;
                };
                g.fill(px, py, px + cell, py + cell, fill);
            }
        }
    }

    private static int brighten(int argb, int amount) {
        int a = argb & 0xff000000;
        int r = Math.min(255, ((argb >> 16) & 0xff) + amount);
        int gg = Math.min(255, ((argb >> 8) & 0xff) + amount);
        int b = Math.min(255, (argb & 0xff) + amount);
        return a | (r << 16) | (gg << 8) | b;
    }
